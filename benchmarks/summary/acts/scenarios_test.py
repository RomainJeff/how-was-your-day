def act(name, target=None, agent=None, note=None):
    entry = {"act": name, "target": target, "agent": agent}
    if note:
        entry["optional"] = True
        entry["note"] = note
    return entry


def turn(tag, speaker, fr, en, mixed="=fr", gap=None, acts=()):
    return {"tag": tag, "speaker": speaker, "fr": fr, "en": en, "mixed": mixed, "gap": gap, "acts": list(acts)}


